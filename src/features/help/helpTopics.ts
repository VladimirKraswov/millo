export function searchHelp(query: string): readonly HelpTopic[] {
  const words = query.toLocaleLowerCase("ru").trim().split(/\s+/).filter(Boolean);
  return helpTopics.filter((topic) => {
    const text = [topic.title, topic.summary, topic.category, ...topic.paragraphs].join(" ").toLocaleLowerCase("ru");
    return words.every((word) => text.includes(word));
  });
}
